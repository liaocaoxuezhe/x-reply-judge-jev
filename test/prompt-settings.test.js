const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const legacy = "Was this short social media reply most likely written or generated by an AI language model rather than by a human?";
function settingsContext(settings) {
  const context = vm.createContext({
    chrome: { storage: { local: { get: async () => ({ settings, apiKey: "test-key" }) } } }
  });
  for (const file of ["api.js", "store.js"]) {
    vm.runInContext(fs.readFileSync(path.join(__dirname, "..", file), "utf8"), context);
  }
  return context;
}

test("saved original prompt upgrades to the current default without changing endpoint or model", async () => {
  const context = settingsContext({ instructions: legacy, model: "jev-1.13.0", baseUrl: "https://example.com" });
  const settings = await vm.runInContext("loadSettings()", context);
  assert.notEqual(settings.instructions, legacy);
  assert.equal(settings.instructions, context.JevApi.DEFAULT_API_SETTINGS.instructions);
  assert.equal(settings.model, "jev-1.13.0");
  assert.equal(settings.baseUrl, "https://example.com");
  assert.equal(settings.apiKey, "test-key");
});

test("saved contrast default upgrades to the current prompt", async () => {
  const previous = JSON.parse(fs.readFileSync(path.join(__dirname, "prompt-eval-2026-10-20/round2-prompts.json"), "utf8")).contrast;
  const context = settingsContext({ instructions: previous, triggerMode: "manual", dailyAutoLimit: 25 });
  const settings = await vm.runInContext("loadSettings()", context);
  assert.notEqual(settings.instructions, previous);
  assert.equal(settings.instructions, context.JevApi.DEFAULT_API_SETTINGS.instructions);
  assert.equal(settings.triggerMode, "manual");
  assert.equal(settings.dailyAutoLimit, 25);
});

