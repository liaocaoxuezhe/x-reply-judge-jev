test("user-customized instructions survive a default prompt upgrade", async () => {
  const context = settingsContext({ instructions: "My custom classification rules." });
  const settings = await vm.runInContext("loadSettings()", context);
  assert.equal(settings.instructions, "My custom classification rules.");
});

test("fresh settings use the same prompt that is sent in API requests", async () => {
  const context = settingsContext({});
  const settings = await vm.runInContext("loadSettings()", context);
  const request = context.JevApi.buildRequestBody("测试原文", settings);
  assert.equal(request.state, "测试原文");
  assert.equal(request.questions.ai_generated.instructions, settings.instructions);
});
